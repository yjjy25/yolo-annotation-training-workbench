const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const path=require('node:path');
const source=fs.readFileSync(path.join(__dirname,'main.cjs'),'utf8');
const start=source.indexOf('const thumbnailCache=new Map();');
const end=source.indexOf("ipcMain.handle('desktop:images'",start);
let encodes=0;
const ctx={fs:{statSync:()=>({mtimeMs:123})},path,nativeImage:{createFromPath:location=>({isEmpty:()=>false,resize:()=>({toDataURL:()=>{encodes++;return location;}})})}};
vm.createContext(ctx);vm.runInContext(source.slice(start,end),ctx);
const tile={width:300,height:200};ctx.tile=tile;
const first=vm.runInContext("thumbnailFor('/project-a/images','same.png',tile)",ctx);
const second=vm.runInContext("thumbnailFor('/project-b/images','same.png',tile)",ctx);
assert.notEqual(first,second,'Projects with matching names and timestamps must not share thumbnails');
vm.runInContext("thumbnailFor('/project-a/images','same.png',tile)",ctx);
assert.equal(encodes,2,'A repeated request should use the cache');
console.log('Passed cross-project thumbnail and cache regression');

// Mixed projects must show video controls only for the displayed video frame.
const workflow=fs.readFileSync(path.join(__dirname,'workflow-tools.js'),'utf8');
const nodes=new Map(),getNode=selector=>{if(!nodes.has(selector))nodes.set(selector,{value:'',max:0,disabled:false,hidden:false,textContent:'',insertBefore(){}});return nodes.get(selector);};
const videoContext={window:{},state:{project:{root:'project-a'}},editor:{name:'clip-0.jpg'},$:getNode};
vm.createContext(videoContext);
vm.runInContext(workflow.slice(workflow.indexOf(' let sequences='),workflow.indexOf(' async function openFrame')),videoContext);
vm.runInContext("sequenceRoot='project-a';sequences=[{id:'clip',frames:[{name:'clip-0.jpg',frame:0,seconds:0},{name:'clip-1.jpg',frame:10,seconds:1}]}];syncTimeline()",videoContext);
assert.equal(getNode('#video-timeline').hidden,false);
assert.equal(getNode('#video-next').disabled,false);
assert.match(getNode('#video-time').textContent,/1\/2/);
videoContext.editor.name='cat_lying_010.jpg';vm.runInContext('syncTimeline()',videoContext);
assert.equal(getNode('#video-timeline').hidden,true,'Ordinary photos in a mixed project must hide the timeline');
assert.equal(getNode('#video-time').textContent,'');
assert.equal(getNode('#video-next').disabled,true);
assert.equal(vm.runInContext('sequence',videoContext),null,'Photo navigation must not retain a video sequence');
videoContext.editor.name='clip-1.jpg';vm.runInContext('syncTimeline()',videoContext);
assert.equal(getNode('#video-timeline').hidden,false);
assert.match(getNode('#video-time').textContent,/2\/2/);
videoContext.state.project.root='project-b';vm.runInContext('syncTimeline()',videoContext);
assert.equal(getNode('#video-timeline').hidden,true,'A sequence from another project must never appear');
videoContext.state.project.root='project-a';videoContext.editor.name=null;vm.runInContext('syncTimeline()',videoContext);
assert.equal(getNode('#video-timeline').hidden,true,'Clearing the canvas must clear the timeline');
console.log('Passed mixed photo/video timeline and project isolation regression');
